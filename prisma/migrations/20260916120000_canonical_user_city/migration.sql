-- Канонические названия пилотных городов в users.city.
--
-- Раньше город был свободной строкой, и подбор недели сравнивал его с
-- каталогом буква в букву: «Belgrade» или «белград » не совпадали с
-- «Белград» у впечатлений, и подборка тихо считалась неосуществимой.
-- Теперь приложение пишет знакомый город русским именем из lib/cities.ts
-- (canonicalCity); эта миграция приводит к тому же виду уже сохранённое.
--
-- Нормализация повторяет normalizeCity: trim, нижний регистр, дефисы и
-- тире → пробел, повторные пробелы → один. Список написаний — aliases из
-- lib/cities.ts; добавишь город туда — допиши и сюда новой миграцией.
-- Незнакомые города не трогаем: потерять ввод человека хуже, чем не узнать.
-- Схема не меняется — только данные.

UPDATE "users" AS u
SET "city" = m.canonical
FROM (
  VALUES
    ('белград', 'Белград'),
    ('beograd', 'Белград'),
    ('belgrade', 'Белград'),
    ('belgrado', 'Белград'),
    ('нови сад', 'Нови-Сад'),
    ('novi sad', 'Нови-Сад'),
    ('ереван', 'Ереван'),
    ('yerevan', 'Ереван'),
    ('ereván', 'Ереван'),
    ('erevan', 'Ереван')
) AS m(alias, canonical)
WHERE u."city" IS NOT NULL
  AND regexp_replace(
        regexp_replace(lower(btrim(u."city")), '[-–—]', ' ', 'g'),
        '\s+', ' ', 'g'
      ) = m.alias
  AND u."city" IS DISTINCT FROM m.canonical;
