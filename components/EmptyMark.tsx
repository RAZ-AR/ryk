import styles from "./EmptyMark.module.css";

/*
 * Знак пустого состояния — контур билета, которого ещё нет.
 *
 * Один знак на все пустые экраны, а не свой для каждого: пусто в ленте,
 * в желаниях и в памяти — это всегда одно и то же «истории пока нет»,
 * и три разных рисунка сообщали бы разницу, которой нет.
 *
 * Почему билет, а не абстрактная фигура: это сигнатурная форма продукта
 * (§6), и пустой контур читается как ожидание, а не как ошибка. Пунктир
 * и приглушённый цвет держат его тише текста рядом — знак сопровождает
 * фразу, а не спорит с ней за внимание.
 */
export function EmptyMark() {
  return (
    <svg className={styles.mark} viewBox="0 0 56 70" aria-hidden="true" focusable="false">
      {/*
       * Только контур и линия отрыва. Вырезы перфорации и штрихкод здесь
       * были и убраны: на 56px дуги вырезов превращаются в мелкие зазубрины,
       * а три полоски штрихкода — в сор. Билет опознаётся по пропорции и
       * поперечной линии, остальное — детали, которых на этом размере нет.
       */}
      <rect x="1" y="1" width="54" height="68" className={styles.outline} />
      <path d="M1 47 H55" className={styles.perforation} />
    </svg>
  );
}
