import type { LifeCategory } from "@/generated/prisma/enums";
import styles from "./CategoryIcon.module.css";

/*
 * Пиктограмма категории впечатления.
 *
 * Знаки не придуманы заново: каждый — сжатый до 16px мотив того же узора,
 * которым категория рисуется в слоте фото (`ExperiencePattern`). Холмы
 * остаются холмами, ступени — ступенями, круги от камня — кругами от камня.
 * Иначе у одной сущности было бы два несвязанных визуальных языка: один
 * на карточке крупно, другой рядом с подписью мелко.
 *
 * Правила рисования — те же, что у узоров: сетка 16×16, штрих 1.5, только
 * окружности и прямые, никаких деталей мельче 1px. Цвет не задаётся —
 * знак наследует `currentColor` от подписи, рядом с которой стоит.
 *
 * Розового акцента здесь нет намеренно, хотя у узоров он есть: на 12px
 * розовая крапина читается как грязь на бумаге, а не как акцент.
 */

type Size = "s" | "m";

type Props = {
  category: LifeCategory;
  /** `s` — 12px рядом с подписью корешка, `m` — 28px в кружке карусели. */
  size?: Size;
};

const SHAPES: Record<LifeCategory, React.ReactNode> = {
  /*
   * Холмы и вода — вложенные дуги (узор: дуги разной высоты). Вершины
   * разведены на 5.5 единиц: при разнице в две дуги слипались на 12px
   * в одну толстую бровь, и мотив «вложенности» пропадал.
   */
  NATURE: (
    <>
      <path d="M1 12.5 Q8 2.5 15 12.5" />
      <path d="M4.5 12.5 Q8 8 11.5 12.5" />
    </>
  ),

  // Колоннада — вертикали разной высоты (узор: корешки книг на полке).
  CULTURE: (
    <>
      <path d="M3 13 V6" />
      <path d="M6.5 13 V3" />
      <path d="M10 13 V7.5" />
      <path d="M13.5 13 V4.5" />
    </>
  ),

  // Движение — параллельные диагонали, как в узоре.
  MOVEMENT: (
    <>
      <path d="M2 13.5 L6 2.5" />
      <path d="M7 13.5 L11 2.5" />
      <path d="M12 13.5 L15.5 4" />
    </>
  ),

  // Связь — пересекающиеся окружности.
  CONNECTION: (
    <>
      <circle cx="6" cy="8" r="4.2" />
      <circle cx="10" cy="8" r="4.2" />
    </>
  ),

  // Радость — лучи из одной точки.
  JOY: (
    <>
      <path d="M8 1.5 V4.5" />
      <path d="M8 11.5 V14.5" />
      <path d="M1.5 8 H4.5" />
      <path d="M11.5 8 H14.5" />
      <path d="M3.4 3.4 L5.5 5.5" />
      <path d="M10.5 10.5 L12.6 12.6" />
      <path d="M12.6 3.4 L10.5 5.5" />
      <path d="M5.5 10.5 L3.4 12.6" />
    </>
  ),

  // Открытие — сетка, в которой одна клетка отмечена.
  DISCOVERY: (
    <>
      <rect x="2.5" y="2.5" width="11" height="11" />
      <path d="M8 2.5 V13.5" />
      <path d="M2.5 8 H13.5" />
      <rect className={styles.solid} x="8" y="2.5" width="5.5" height="5.5" />
    </>
  ),

  // Вызов — ступени вверх.
  CHALLENGE: <path d="M2 13.5 H6 V9.5 H10 V5.5 H14 V2" />,

  /*
   * Покой — горизонтали, редеющие кверху. Зазоры растут 2.5 → 3.5 → 5,
   * длина убывает: четыре равноотстоящие линии одинаковой длины — это
   * иконка меню, и на 12px её ни с чем другим не спутать было нельзя.
   */
  REST: (
    <>
      <path d="M2 14 H14" />
      <path d="M3 11.5 H13" />
      <path d="M4 8 H12" />
      <path d="M5 3 H11" />
    </>
  ),

  // Вклад — круги, расходящиеся от брошенного камня.
  CONTRIBUTION: (
    <>
      <circle cx="8" cy="8" r="6" />
      <circle cx="8" cy="8" r="3" />
      <circle className={styles.solid} cx="8" cy="8" r="1.1" />
    </>
  ),
};

export function CategoryIcon({ category, size = "s" }: Props) {
  return (
    <svg
      className={[styles.icon, styles[size]].join(" ")}
      viewBox="0 0 16 16"
      // Подпись категории всегда стоит рядом словами, поэтому знак —
      // украшение строки, а не её смысл: скринридеру он не нужен.
      aria-hidden="true"
      focusable="false"
    >
      {SHAPES[category]}
    </svg>
  );
}
