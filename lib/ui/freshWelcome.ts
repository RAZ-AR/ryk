/*
 * Одноразовая строка «а историю недели выберем вместе» на главной сразу
 * после онбординга (22-daily-joy-plan, фаза 3).
 *
 * Почему не отдельный финальный экран онбординга: completeOnboarding
 * делает revalidatePath("/"), и Next в ответе server action сразу
 * перерисовывает маршрут — OnboardingFlow сменяется главной раньше, чем
 * успел бы показать свой финал. А на главной «Лист дня» и так стоит
 * первым, с настоящими данными нового человека. Не хватает одного —
 * тёплой строки, что неделю мы выберем вместе. Её и переносим сюда.
 *
 * Почему sessionStorage, а не поле в БД: это не данные о человеке, а
 * мгновение перехода. Ставим метку до сохранения (ответ action может
 * перерисовать дерево раньше, чем код после await успеет выполниться),
 * главная забирает её один раз. Хранилище недоступно — строки просто нет.
 */

const KEY = "ryk:fresh-welcome";

export function markFreshWelcome(): void {
  try {
    sessionStorage.setItem(KEY, "1");
  } catch {
    // Приватный режим или запрет хранилища: строка — украшение, не ошибка.
  }
}

export function clearFreshWelcome(): void {
  try {
    sessionStorage.removeItem(KEY);
  } catch {
    // То же, что выше: без хранилища и снимать нечего.
  }
}

/**
 * Есть ли метка. Только читает: снимает её clearFreshWelcome из эффекта.
 * Чтение и снятие разведены, потому что инициализатор useState в
 * StrictMode зовётся дважды — снимай он метку сам, второй вызов уже
 * вернул бы false, и строка не показалась бы никогда.
 */
export function peekFreshWelcome(): boolean {
  try {
    return sessionStorage.getItem(KEY) === "1";
  } catch {
    return false;
  }
}
